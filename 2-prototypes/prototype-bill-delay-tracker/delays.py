#!/usr/bin/env python3
"""Join text versions with CRS summaries and compute summary lag per bill and stage.

Reads versions.csv, pages.csv, summaries.csv from --data-dir; writes delays.csv,
awaiting.csv and stats.json there. Stdlib only.

Lag definition: summary.last_summary_update_date minus version.date_ingested, matched by
stage (introduced / reported / passed / enrolled). date_ingested (GovInfo MODS, collected into
ingest.csv) is the day the text appeared on GovInfo; date_issued, the date printed on the bill,
is kept as printed_date and is the fallback when no ingest date was collected. The summary date
is the one the Congress.gov API documents as "the date the bill summary was last updated"; the
API exposes no first-publication date, so a summary revised later reads slower than it was.
The API exposes no "first published" date for a summary, only its last update,
so a summary CRS revised later reads as a longer lag than the user actually
waited. date_issued is the date printed on the version, not the day GPO posted it.
"""
import argparse
import csv
import json
import statistics
from collections import Counter, defaultdict
from datetime import date, datetime, timezone
from pathlib import Path

VERSION_STAGE = {"ih": "introduced", "is": "introduced", "rh": "reported", "rs": "reported",
                 "eh": "passed", "es": "passed", "eah": "passed", "eas": "passed", "enr": "enrolled"}
STAGE_ORDER = ["introduced", "reported", "passed", "enrolled"]


def summary_stage(action_desc):
    d = action_desc.lower()
    if d.startswith("introduced"):
        return "introduced"
    if d.startswith("reported"):
        return "reported"
    if d.startswith("passed"):
        return "passed"
    if d.startswith("public law") or d.startswith("enrolled"):
        return "enrolled"
    if d.startswith("house agreed to senate amendment") or d.startswith("senate agreed to house amendment"):
        return "passed"
    return None


def read_csv(path):
    if not path.exists():
        return []
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def write_csv(path, rows, fields):
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def to_date(s):
    return date.fromisoformat(s[:10]) if s else None


def histogram(values, edges):
    """Counts per bin; the last bin is open-ended."""
    bins = []
    for i, lo in enumerate(edges):
        hi = edges[i + 1] if i + 1 < len(edges) else None
        n = sum(1 for v in values if v >= lo and (hi is None or v < hi))
        bins.append({"from": lo, "to": hi, "count": n})
    return bins


DELAYS_JS_HEADER = """\
// Generated by delays.py. Do not edit; rerun delays.py.
//
// This is delays.json wrapped as a script so that dashboard/index.html works when opened straight
// from disk: browsers block fetch() of local files on file:// pages but allow <script src>. The
// document is a JSON string passed to JSON.parse, not an object literal, because JSON parses
// faster than JavaScript source for data this large. Read delays.json for the plain data.
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-dir", type=Path, default=Path(__file__).parent / "data")
    ap.add_argument("--as-of", default=date.today().isoformat(), help="date used for 'awaiting' ages")
    a = ap.parse_args()
    as_of = date.fromisoformat(a.as_of)

    versions = read_csv(a.data_dir / "versions.csv")
    pages = {r["package_id"]: int(r["pages"]) for r in read_csv(a.data_dir / "pages.csv") if r["pages"].isdigit()}
    ingested = {r["package_id"]: r["date_ingested"] for r in read_csv(a.data_dir / "ingest.csv") if r["date_ingested"]}
    summaries = read_csv(a.data_dir / "summaries.csv")

    def published(v):
        """The day the text appeared on GovInfo (MODS dateIngested), else the printed date."""
        return ingested.get(v["package_id"]) or v["date_issued"]

    def summary_date(s):
        """What the API documents as the date the summary was last updated; updateDate is the
        Congress.gov record's update, which runs later for a few percent of summaries."""
        return s["last_summary_update_date"] or s["update_date"]

    # earliest text version per (bill, stage)
    text = {}
    bills_with_text = set()
    reported = set()
    for v in versions:
        bill = (v["bill_type"], v["number"])
        bills_with_text.add(bill)
        if v["version"] in ("rh", "rs"):
            reported.add(bill)
        stage = VERSION_STAGE.get(v["version"])
        if not stage:
            continue
        k = bill + (stage,)
        if k not in text or v["date_issued"] < text[k]["date_issued"]:
            text[k] = v

    # earliest summary update per (bill, stage)
    summ = {}
    bills_summarized = set()
    for s in summaries:
        stage = summary_stage(s["action_desc"])
        if not stage:
            continue
        bill = (s["bill_type"], s["number"])
        bills_summarized.add(bill)
        k = bill + (stage,)
        if k not in summ or summary_date(s) < summary_date(summ[k]):
            summ[k] = s

    delays = []
    for k, v in sorted(text.items()):
        s = summ.get(k)
        if not s:
            continue
        td, sd = to_date(published(v)), to_date(summary_date(s))
        delays.append({"bill_type": k[0], "number": k[1], "stage": k[2], "package_id": v["package_id"],
                       "text_date": td.isoformat(), "printed_date": v["date_issued"], "summary_date": sd.isoformat(),
                       "delay_days": (sd - td).days, "pages": pages.get(v["package_id"], ""),
                       "title": v["title"]})
    write_csv(a.data_dir / "delays.csv", delays,
              ["bill_type", "number", "stage", "package_id", "text_date", "printed_date", "summary_date", "delay_days", "pages", "title"])

    awaiting = []
    for k, v in sorted(text.items()):
        if k[2] == "introduced" and k not in summ:
            td = to_date(published(v))
            awaiting.append({"bill_type": k[0], "number": k[1], "package_id": v["package_id"],
                             "text_date": td.isoformat(), "printed_date": v["date_issued"], "age_days": (as_of - td).days,
                             "pages": pages.get(v["package_id"], ""), "title": v["title"]})
    awaiting.sort(key=lambda r: -r["age_days"])
    write_csv(a.data_dir / "awaiting.csv", awaiting,
              ["bill_type", "number", "package_id", "text_date", "printed_date", "age_days", "pages", "title"])

    # one record per text version for the dashboard. Only the earliest edition of a
    # (bill, stage) carries the stage and its lag; every other edition keeps its pages
    # under stage null so "pages processed" counts the whole Congress.
    earliest = {v["package_id"]: k for k, v in text.items()}
    records = []
    for v in sorted(versions, key=lambda v: (v["bill_type"], int(v["number"]), v["date_issued"])):
        k = earliest.get(v["package_id"])
        s = summ.get(k) if k else None
        td = to_date(published(v))
        sd = to_date(summary_date(s)) if s else None
        records.append({"type": v["bill_type"], "number": v["number"], "stage": k[2] if k else None,
                        "text_date": td.isoformat(), "printed_date": v["date_issued"],
                        "summary_date": sd.isoformat() if sd else None,
                        "lag_days": (sd - td).days if sd else None,
                        "pages": pages.get(v["package_id"]),
                        "reported": (v["bill_type"], v["number"]) in reported,
                        "title": v["title"]})
    before_text = Counter(k[2] for k in summ if k not in text)
    envelope = {"as_of": as_of.isoformat(), "congress": versions[0]["congress"] if versions else None,
                "summary_before_text": dict(sorted(before_text.items())),
                # how many text versions fell back to the printed date for want of an ingest date
                "versions_without_ingest_date": sum(1 for v in versions if v["package_id"] not in ingested),
                "records": records}
    envelope_json = json.dumps(envelope, separators=(",", ":"))
    (a.data_dir / "delays.json").write_text(envelope_json + "\n")
    # The same document again as a script the dashboard can load from disk. Browsers refuse fetch()
    # on file:// pages, so a dashboard opened by double-clicking index.html cannot read delays.json;
    # a classic <script src> tag has no such restriction. The document travels as a JSON string
    # handed to JSON.parse rather than as a bare object literal because engines parse JSON faster
    # than JavaScript source at this size (several MB). json.dumps of the JSON text yields a valid
    # JavaScript string literal: quotes and backslashes escaped, non-ASCII as \uXXXX.
    (a.data_dir / "delays.js").write_text(DELAYS_JS_HEADER + "window.BILL_DELAYS = JSON.parse("
                                          + json.dumps(envelope_json) + ");\n")

    by_stage = defaultdict(list)
    for d in delays:
        by_stage[d["stage"]].append(d["delay_days"])
    stage_stats = {}
    for stage in STAGE_ORDER:
        xs = by_stage.get(stage, [])
        if xs:
            stage_stats[stage] = {"n": len(xs), "mean": round(statistics.mean(xs), 1),
                                  "median": statistics.median(xs), "max": max(xs), "min": min(xs)}
    # by month of introduction: how many got a summary, how many still wait, and the lag
    # among those summarized. Recent months are right-censored: only the fast ones count.
    months = defaultdict(lambda: {"summarized": 0, "awaiting": 0, "lags": []})
    for d in delays:
        if d["stage"] == "introduced":
            m = months[d["text_date"][:7]]
            m["summarized"] += 1
            m["lags"].append(d["delay_days"])
    for r in awaiting:
        months[r["text_date"][:7]]["awaiting"] += 1
    monthly = []
    for month in sorted(months):
        m = months[month]
        xs = sorted(m["lags"])
        monthly.append({"month": month, "summarized": m["summarized"], "awaiting": m["awaiting"],
                        "median_lag": statistics.median(xs) if xs else None,
                        "p90_lag": xs[min(len(xs) - 1, int(len(xs) * 0.9))] if xs else None})
    all_delays = [d["delay_days"] for d in delays]
    intro = by_stage.get("introduced", [])
    known_pages = [pages[v["package_id"]] for v in versions if v["package_id"] in pages]
    stats = {
        "as_of": as_of.isoformat(),
        "computed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "congress": versions[0]["congress"] if versions else None,
        "bills_with_text": len(bills_with_text),
        "text_versions": len(versions),
        "bills_summarized": len(bills_summarized),
        "bills_reported_by_committee": len(reported),
        "introduced_with_summary": len(intro),
        "introduced_awaiting_summary": len(awaiting),
        "pages": {"versions_with_count": len(known_pages), "versions_total": len(versions),
                  "total": sum(known_pages), "mean": round(statistics.mean(known_pages), 1) if known_pages else None},
        "delay_days": {"n": len(all_delays), "mean": round(statistics.mean(all_delays), 1) if all_delays else None,
                       "median": statistics.median(all_delays) if all_delays else None,
                       "max": max(all_delays) if all_delays else None},
        "by_stage": stage_stats,
        "introduced_histogram": histogram(intro, [0, 7, 14, 30, 60, 90, 180, 365]),
        "awaiting_histogram": histogram([r["age_days"] for r in awaiting], [0, 7, 14, 30, 60, 90, 180, 365]),
        "monthly_introduced": monthly,
        "summaries_collected": len(summaries),
        "caveats": [
            "delay = summary last-update date minus the date printed on the text version; the API has no first-published date for summaries, so revised summaries overstate the lag",
            "'awaiting' means no introduced-stage summary appears in the summaries collected so far; a partial summaries sweep inflates it",
            "page counts come from GovInfo package summaries, one call per version, and may cover only a sample",
        ],
    }
    (a.data_dir / "stats.json").write_text(json.dumps(stats, indent=1) + "\n")
    print(json.dumps({k: stats[k] for k in ("bills_with_text", "bills_summarized", "introduced_with_summary",
                                             "introduced_awaiting_summary", "delay_days", "by_stage")}, indent=1))


if __name__ == "__main__":
    main()
